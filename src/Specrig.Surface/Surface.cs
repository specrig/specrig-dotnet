using Microsoft.CodeAnalysis.MSBuild;

namespace Specrig;

public sealed class Surface
{
    public const string Format = "surface/1";

    public string Service { get; init; } = "";
    public SortedSet<string> Publishes { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Consumes { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Serves { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Calls { get; } = new(StringComparer.Ordinal);
    public SortedDictionary<string, SortedSet<string>> Clients { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Settings { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Optional { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Sections { get; } = new(StringComparer.Ordinal);
    public SortedSet<string> Consumers { get; } = new(StringComparer.Ordinal);
    public SortedDictionary<string, string> Descriptors { get; } = new(StringComparer.Ordinal);

    public static async Task<Surface> Extract(string project, string service)
    {
        using var workspace = MSBuildWorkspace.Create();
        var loaded = await workspace.OpenProjectAsync(Path.GetFullPath(project));
        if (workspace.Diagnostics.Where(d => d.Kind == Microsoft.CodeAnalysis.WorkspaceDiagnosticKind.Failure).ToList() is { Count: > 0 } failures)
        {
            throw new InvalidOperationException($"{project} does not load: {string.Join("; ", failures.Select(f => f.Message))}");
        }
        var compilation = await loaded.GetCompilationAsync() ?? throw new InvalidOperationException($"{project} does not compile");
        if (compilation.GetDiagnostics().Where(d => d.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error).Take(5).ToList() is { Count: > 0 } errors)
        {
            throw new InvalidOperationException($"{project} does not compile: {string.Join("; ", errors)}");
        }
        return new Walker(compilation, service).Run();
    }

    public string Encode() => "# Generated by `specrig surface` from the service's code.\n" + Yaml.Emit(new Mapping
    {
        { "specrig", Format },
        { "service", Service },
        { "publishes", Publishes.ToList() },
        { "consumes", Consumes.ToList() },
        { "serves", Serves.ToList() },
        { "calls", Calls.ToList() },
        { "clients", Lists(Clients) },
    });

    public string EncodeChecks() => "# Generated by `specrig surface` from the service's code: what its boot is checked against.\n" + Yaml.Emit(new Mapping
    {
        { "specrig", "checks/1" },
        { "service", Service },
        { "settings", Settings.ToList() },
        { "optional", Optional.ToList() },
        { "sections", Sections.ToList() },
        { "consumers", Consumers.ToList() },
    });

    static Mapping Lists(SortedDictionary<string, SortedSet<string>> lists)
    {
        var mapping = new Mapping();
        foreach (var (key, values) in lists)
        {
            mapping.Add(key, values.ToList());
        }
        return mapping;
    }

    public static bool Rewrite(string file, string body)
    {
        if (File.Exists(file) && File.ReadAllText(file) == body)
        {
            return false;
        }
        Directory.CreateDirectory(Path.GetDirectoryName(file)!);
        File.WriteAllText(file, body);
        return true;
    }
}
