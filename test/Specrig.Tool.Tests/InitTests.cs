namespace Specrig.Tool.Tests;

public class InitTests
{
    readonly string repo;
    readonly string work = Path.Combine(AppContext.BaseDirectory, "work", Guid.NewGuid().ToString("N"));

    public InitTests()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (!File.Exists(Path.Combine(dir.FullName, "Specrig.slnx")))
        {
            dir = dir.Parent!;
        }
        repo = dir.FullName;
        Directory.CreateDirectory(Path.Combine(work, ".git"));
    }

    string Copied(string source, string service)
    {
        var target = Path.Combine(work, service);
        foreach (var file in Directory.EnumerateFiles(source, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(source, file);
            if (rel.Split(Path.DirectorySeparatorChar) is ["bin" or "obj", ..])
            {
                continue;
            }
            var copy = Path.Combine(target, "src", rel);
            Directory.CreateDirectory(Path.GetDirectoryName(copy)!);
            File.Copy(file, copy);
        }
        return target;
    }

    string Reminders() => Copied(Path.Combine(repo, "samples", "reminders", "src"), "reminders");

    string Gateway() => Copied(Path.Combine(repo, "test", "fixtures", "gateway", "src"), Path.Combine("services", "gateway"));

    static string Read(string service, string path) => File.ReadAllText(Path.Combine(service, path));

    [Fact]
    public async Task Init_lays_the_harness_out_from_what_the_code_reads()
    {
        var service = Reminders();

        Assert.Equal(0, await Init.Run([service, "--backend", "billing=Billing:BaseUrl", "--contract", "billing=../docs/billing.yaml"]));

        var harness = Read(service, "tests/internal/Harness.cs");
        Assert.Contains("public override string Service => \"reminders\";", harness);
        Assert.Contains("public Backend Billing { get; } = new(\"https://billing.reminders.test\")", harness);
        Assert.Contains("Setting = \"Billing:BaseUrl\",", harness);
        Assert.Contains("public RabbitBus Bus { get; } = new(\"ConnectionStrings:Rabbit\");", harness);
        Assert.Contains("protected override Workers Running => [typeof(global::Reminders.InvoicesPaid)];", harness);
        var project = Read(service, "tests/Specs.csproj");
        Assert.Contains("<ProjectReference Include=\"../src/Reminders.csproj\" />", project);
        Assert.Contains("$(SpecrigCheckout)/src/Specrig.RabbitMQ/Specrig.RabbitMQ.csproj", project);
        var specrig = Read(service, "specrig.md");
        Assert.Contains("| spec | `tests/feature/**/*.feature` |", specrig);
        Assert.Contains("| csproj | `tests/Specs.csproj` | platform | redgreen |", specrig);
        Assert.DoesNotContain("{{", specrig);
        Assert.DoesNotContain("\n\n\n", specrig);
        Assert.StartsWith("# Generated by `specrig surface`", Read(service, "tests/surface.yaml"));
        Assert.False(File.Exists(Path.Combine(service, "Makefile")));
    }

    const string Reference = "Read @specrig.md before the first edit: Rule #11, and how this service's suite runs.";

    static async Task<string> Said(Func<Task> run)
    {
        var said = new StringWriter();
        var was = Console.Out;
        Console.SetOut(said);
        try
        {
            await run();
        }
        finally
        {
            Console.SetOut(was);
        }
        return said.ToString();
    }

    [Fact]
    public async Task Init_writes_an_AGENTS_md_of_the_service_s_own_that_brings_specrig_md_in()
    {
        var service = Reminders();

        var said = await Said(() => Init.Run([service, "--backend", "billing=Billing:BaseUrl"]));

        var stub = Read(service, "AGENTS.md");
        Assert.StartsWith($"# AGENTS.md\n\nInstructions for AI coding agents working in reminders.\n\n{Reference}\n\n## This service\n", stub);
        Assert.Equal("ok", Shared.Verdict(stub));
        Assert.Contains("+ AGENTS.md\n+ specrig.md\n", said);
    }

    [Fact]
    public async Task Init_adds_the_line_that_brings_specrig_md_in_to_the_end_of_an_AGENTS_md_that_lacks_it()
    {
        var service = Reminders();
        File.WriteAllText(Path.Combine(service, "AGENTS.md"), "ours");

        var said = await Said(() => Init.Run([service, "--backend", "billing=Billing:BaseUrl"]));

        Assert.Equal($"ours\n\n{Reference}\n", Read(service, "AGENTS.md"));
        Assert.Contains("~ AGENTS.md: the line that brings specrig.md in, at its end\n", said);
    }

    [Fact]
    public async Task Init_says_what_is_left_of_an_AGENTS_md_that_still_carries_Rule_11()
    {
        var service = Reminders();
        File.WriteAllText(Path.Combine(service, "AGENTS.md"), "# AGENTS.md\n\n## Rule #11 — specification before code\n");

        var said = await Said(() => Init.Run([service, "--backend", "billing=Billing:BaseUrl"]));

        Assert.Contains("it still carries Rule #11, which specrig.md holds now: keep the service's own sections in it and delete the rest", said);
        Assert.StartsWith("AGENTS.md still carries Rule #11", Assert.Throws<InvalidOperationException>(() => Init.Agents([service])).Message);
    }

    [Fact]
    public async Task Specrig_md_holds_nothing_init_was_told_so_agents_writes_it_as_init_did()
    {
        var service = Reminders();
        await Init.Run([service, "--backend", "billing=Billing:BaseUrl", "--contract", "billing=../docs/billing.yaml"]);
        var written = Read(service, "specrig.md");

        var said = await Said(() => Task.FromResult(Init.Agents([service])));

        Assert.DoesNotContain("billing", written, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("reminders", written);
        Assert.DoesNotContain("`make ", written);
        Assert.StartsWith("# specrig.md\n\n", written);
        Assert.Equal("= specrig.md\n", said);
        Assert.Equal(written, Read(service, "specrig.md"));
    }

    [Fact]
    public void Agents_fails_while_AGENTS_md_does_not_bring_specrig_md_in_and_writes_specrig_md_all_the_same()
    {
        var service = Reminders();
        File.WriteAllText(Path.Combine(service, "AGENTS.md"), "ours\n");

        var refused = Assert.Throws<InvalidOperationException>(() => Init.Agents([service]));

        Assert.StartsWith($"AGENTS.md does not bring specrig.md in: add the line\n\n{Reference}\n\n", refused.Message);
        Assert.True(File.Exists(Path.Combine(service, "specrig.md")));
    }

    [Fact]
    public void Agents_writes_nothing_where_there_is_no_AGENTS_md()
    {
        var service = Reminders();

        Assert.StartsWith("there is no AGENTS.md here", Assert.Throws<ArgumentException>(() => Init.Agents([service])).Message);
        Assert.False(File.Exists(Path.Combine(service, "specrig.md")));
    }

    [Fact]
    public async Task Init_names_the_tool_the_specrig_plugin_asks()
    {
        var service = Reminders();

        await Init.Run([service, "--backend", "billing=Billing:BaseUrl"]);

        var marker = Read(service, "specrig.yaml");
        Assert.StartsWith("guard: [dotnet, run, --project, ", marker);
        Assert.EndsWith("/src/Specrig.Tool, --]\n", marker);
        Assert.Contains("`dotnet run --project ", Read(service, "specrig.md"));
    }

    [Fact]
    public async Task Init_keeps_a_marker_it_finds_and_says_what_it_lacks()
    {
        var service = Reminders();
        File.WriteAllText(Path.Combine(service, "specrig.yaml"), "flows:\n  clients:\n    Reminders.Billing: billing\n");
        var said = new StringWriter();
        var was = Console.Out;
        Console.SetOut(said);
        try
        {
            await Init.Run([service, "--backend", "billing=Billing:BaseUrl"]);
        }
        finally
        {
            Console.SetOut(was);
        }

        Assert.Equal("flows:\n  clients:\n    Reminders.Billing: billing\n", Read(service, "specrig.yaml"));
        Assert.Contains("specrig.yaml names no guard: add `guard: [dotnet, run, --project, ", said.ToString());
    }

    [Fact]
    public async Task Init_refuses_a_setting_the_code_does_not_read()
    {
        var refused = await Assert.ThrowsAsync<ArgumentException>(() => Init.Run([Reminders(), "--backend", "billing=Billing:Url"]));

        Assert.Equal("the service reads no setting Billing:Url; it reads Billing:BaseUrl, ConnectionStrings:Rabbit", refused.Message);
    }

    [Fact]
    public async Task Init_stands_in_for_neighbours_that_serve_over_grpc_alone()
    {
        var service = Gateway();

        Assert.Equal(0, await Init.Run([service,
            "--grpc", "ausweis=Ausweis:Address", "--serves", "ausweis=customer",
            "--grpc", "herald=Herald:Address", "--serves", "herald=notification.Mail"]));

        var harness = Read(service, "tests/internal/Harness.cs");
        Assert.Contains(
            "public GrpcBackend Ausweis { get; } = new(\"https://ausweis.gateway.test\",\n" +
            "        global::Gateway.Customer.Accounts.Descriptor,\n" +
            "        global::Gateway.Customer.Sessions.Descriptor)\n" +
            "    {\n" +
            "        Setting = \"Ausweis:Address\",\n" +
            "    };",
            harness);
        Assert.Contains("public GrpcBackend Herald { get; } = new(\"https://herald.gateway.test\", global::Gateway.Notification.Mail.Descriptor)", harness);
        Assert.Contains("$(SpecrigCheckout)/src/Specrig.Grpc/Specrig.Grpc.csproj", Read(service, "tests/Specs.csproj"));
        var specrig = Read(service, "specrig.md");
        Assert.Contains("`harness.<Neighbour>.Reply(method, answer)`", specrig);
        Assert.DoesNotContain("Ausweis", specrig);
    }

    [Fact]
    public async Task Init_asks_which_neighbour_serves_what_when_two_could()
    {
        var refused = await Assert.ThrowsAsync<ArgumentException>(() => Init.Run([Gateway(), "--grpc", "ausweis", "--grpc", "herald"]));

        Assert.Equal(
            "which of customer.Accounts, customer.Sessions, notification.Mail does ausweis serve? name them with --serves ausweis=<package or service>",
            refused.Message);
    }

    [Fact]
    public async Task Init_refuses_a_service_whose_http_neighbour_goes_unnamed()
    {
        var refused = await Assert.ThrowsAsync<ArgumentException>(() => Init.Run([Reminders()]));

        Assert.Equal("the service calls GET /invoices, POST /reminders: name the neighbour with --backend <name>[=<setting>]", refused.Message);
    }
}
